#!/usr/bin/env python3
"""Subset the web fonts down to the characters the site actually renders.

The originals in `assets/fonts/` are full Inter and JetBrains Mono faces at
roughly 24 KB each. The site uses 141 distinct characters, so more than half
of every file is glyphs nothing draws. Shipping the full faces costs Largest
Contentful Paint: the browser paints with the fallback, then repaints when the
webfont lands, and that repaint is the LCP event.

Run this after changing copy or adding a post:

    python quality/subset_fonts.py

It writes the subsets to `static/fonts/` and records the codepoints they cover
in `static/fonts/covered-codepoints.txt`. `tests/font_coverage.rs` checks that
every character in the content and the page source is in that file, so a
character the subsets do not carry fails the test suite instead of silently
rendering as a missing glyph.
"""

import glob
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets', 'fonts')
OUT = os.path.join(ROOT, 'static', 'fonts')
COVERAGE = os.path.join(OUT, 'covered-codepoints.txt')

# Text the site renders: content files, page copy in Rust, and the CSS.
SOURCES = ['content/**/*.mdx', 'content/**/*.md', 'content/**/*.toml',
           'src/**/*.rs', 'static/**/*.css', 'static/**/*.svg']

# Characters always worth carrying, whatever the corpus happens to contain.
ALWAYS = (
    ''.join(chr(c) for c in range(0x20, 0x7F))
    + '\u00a0'  # no-break space
    + '\u2018\u2019'  # curly single quotes
    + '\u201c\u201d'  # curly double quotes
    + '\u2013\u2014'  # en and em dash
    + '\u2026'        # ellipsis
    + '\u00b7'        # middle dot
    + '\u2192\u2190\u2191\u2193'  # arrows
    + '\u21d2'        # rightwards double arrow
    + '\u00d7'        # multiplication sign
)


def corpus_characters():
    chars = set(ALWAYS)
    for pattern in SOURCES:
        for path in glob.glob(os.path.join(ROOT, pattern), recursive=True):
            try:
                chars.update(open(path, encoding='utf-8').read())
            except (UnicodeDecodeError, OSError):
                continue
    # Control characters are not glyphs.
    return {c for c in chars if ord(c) >= 0x20 or c in '\t\n' }


def main():
    chars = corpus_characters()
    text = ''.join(sorted(chars))
    print('characters to carry: %d' % len(chars))

    sources = sorted(glob.glob(os.path.join(ASSETS, '*.woff2')))
    if not sources:
        sys.exit('subset_fonts: no fonts in assets/fonts/')
    os.makedirs(OUT, exist_ok=True)

    for src in sources:
        name = os.path.basename(src)
        dest = os.path.join(OUT, name)
        cmd = [sys.executable, '-m', 'fontTools.subset', src,
               '--text=' + text,
               '--layout-features=kern,liga,calt,ccmp,locl,mark,mkmk',
               '--flavor=woff2',
               '--no-hinting',
               '--output-file=' + dest]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            sys.exit('subset_fonts: %s failed\n%s' % (name, result.stderr[-1500:]))
        before, after = os.path.getsize(src), os.path.getsize(dest)
        print('  %-26s %7d -> %6d bytes (%.0f%% smaller)'
              % (name, before, after, 100 * (1 - after / before)))

    with open(COVERAGE, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('# Codepoints the subset fonts carry. Generated by quality/subset_fonts.py.\n')
        for ch in sorted(chars):
            fh.write('U+%04X\n' % ord(ch))
    print('wrote %s (%d codepoints)' % (COVERAGE, len(chars)))


if __name__ == '__main__':
    main()
